import {spawnSync} from 'node:child_process';
import {accessSync,constants} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
if(!process.env.npm_execpath)throw new Error('Use npm run install:ci.');
const result=spawnSync(process.execPath,[process.env.npm_execpath,'ci','--prefix',root,'--workspaces=false','--include=dev','--include=optional','--prefer-offline','--no-audit','--no-fund'],{cwd:root,env:process.env,stdio:'inherit'});
if(result.error)throw result.error;
if(result.status!==0)process.exit(result.status??1);
accessSync(path.join(root,'node_modules/.bin',process.platform==='win32'?'vinext.cmd':'vinext'),process.platform==='win32'?constants.F_OK:constants.X_OK);
console.log('Locked Vinext dependencies installed.');
