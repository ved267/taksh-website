import {spawnSync} from 'node:child_process';
import {accessSync,constants} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
if(!process.env.npm_execpath)throw new Error('Run this installer with npm run install:ci.');
const installed=spawnSync(process.execPath,[process.env.npm_execpath,'ci','--prefix',root,'--workspaces=false','--include=dev','--include=optional','--prefer-offline','--no-audit','--no-fund'],{cwd:root,stdio:'inherit',env:process.env});
if(installed.error)throw installed.error;
if(installed.status!==0)process.exit(installed.status??1);
accessSync(path.join(root,'node_modules','.bin',process.platform==='win32'?'next.cmd':'next'),process.platform==='win32'?constants.F_OK:constants.X_OK);
console.log('Locked Next.js dependencies installed.');
