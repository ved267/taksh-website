// GitHub Actions runs this for claude/* and codex/* branches, independent of agent.
// It explicitly applies committed migrations before deploying; never runs inside a request.
import {readFile,writeFile,mkdir,appendFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {execFileSync} from 'node:child_process';
import {previewIdentity,isolatedPreviewConfig} from '../lib/cloudflare/preview-config.mjs';
import {previewBranchAllowed} from '../lib/cloudflare/deployment-policy.mjs';
import {cloudflareRequest} from './cloudflare-api.mjs';
import {previewUrlFromOutput} from '../lib/cloudflare/preview-output.mjs';
import {compiledPreviewBase,syntheticPreviewSecrets} from '../lib/cloudflare/compiled-preview.mjs';
const root=process.cwd();
const branch=process.env.TAKSH_PREVIEW_BRANCH||process.env.WORKERS_CI_BRANCH||process.env.CF_PAGES_BRANCH||execFileSync('git',['branch','--show-current'],{encoding:'utf8'}).trim();
if(!previewBranchAllowed(branch))throw new Error('Only claude/* and codex/* branches can deploy previews.');
const identity=previewIdentity(branch);
const bundleRoot=process.env.TAKSH_PREVIEW_BUNDLE_ROOT;
const builtPath=resolve(root,'dist/server/wrangler.json');
const base=bundleRoot?compiledPreviewBase(JSON.parse(await readFile(resolve(root,'wrangler.json'),'utf8')),bundleRoot):JSON.parse(await readFile(builtPath,'utf8'));
if(process.env.GITHUB_ACTIONS&&!bundleRoot)throw new Error('Actions previews require a verified compiled bundle and trusted main tooling.');
const account=base.account_id;
if(!/^[a-f0-9]{32}$/.test(account||''))throw new Error('Cloudflare account is not configured.');
const dbs=(await cloudflareRequest(`accounts/${account}/d1/database?per_page=100`)).result;
let db=dbs.find(db=>db.name===identity.databaseName);
if(!db)db=(await cloudflareRequest(`accounts/${account}/d1/database`,{method:'POST',body:{name:identity.databaseName,primary_location_hint:'apac'}})).result;
const buckets=(await cloudflareRequest(`accounts/${account}/r2/buckets`)).result.buckets;
if(!buckets.some(bucket=>bucket.name===identity.bucketName))await cloudflareRequest(`accounts/${account}/r2/buckets`,{method:'POST',body:{name:identity.bucketName,locationHint:'apac',storageClass:'Standard'}});
const config=isolatedPreviewConfig(base,branch,db.uuid);
config.main=resolve(dirname(builtPath),base.main);
config.assets.directory=resolve(dirname(builtPath),base.assets.directory);
config.d1_databases.forEach(binding=>binding.migrations_dir=resolve(bundleRoot||root,'drizzle'));
config.previews.d1_databases.forEach(binding=>binding.migrations_dir=resolve(bundleRoot||root,'drizzle'));
await mkdir(resolve(root,'.local'),{recursive:true});
const configPath=resolve(root,'.local/wrangler-preview.json');
await writeFile(configPath,JSON.stringify(config,null,2));
const wrangler=resolve(root,'node_modules/wrangler/bin/wrangler.js');
function run(args){execFileSync(process.execPath,[wrangler,...args],{stdio:'inherit'});}
console.log(`Isolated synthetic preview: ${branch}; ${identity.databaseName}`);
run(['d1','migrations','apply','DB','--remote','--preview','--config',configPath]);
const fixtureFile=resolve(root,'.local/preview-fixture-secrets.json');
const overrides=process.env.TAKSH_PREVIEW_SECRETS_FILE?JSON.parse(await readFile(resolve(process.env.TAKSH_PREVIEW_SECRETS_FILE),'utf8')):{};
await writeFile(fixtureFile,JSON.stringify({...syntheticPreviewSecrets(),...overrides}),{mode:0o600});
const secretsFile=fixtureFile;
const metadataPath=resolve(root,'.local/preview-deployment-output.jsonl');
await writeFile(metadataPath,'');
execFileSync(process.execPath,[wrangler,'preview','--name',branch,'--config',configPath,'--json','--secrets-file',secretsFile],{encoding:'utf8',stdio:['ignore','pipe','inherit'],maxBuffer:16*1024*1024,env:{...process.env,WRANGLER_OUTPUT_FILE_PATH:metadataPath}});
const url=previewUrlFromOutput(await readFile(metadataPath,'utf8'),branch,base.name);
console.log('Preview URL: '+url);
await writeFile(resolve(root,'.local/preview-url.txt'),url+'\n');
if(process.env.GITHUB_OUTPUT)await appendFile(process.env.GITHUB_OUTPUT,'url='+url+'\n');
if(process.env.GITHUB_STEP_SUMMARY)await appendFile(process.env.GITHUB_STEP_SUMMARY,`Isolated preview for ${branch}: [Open preview](${url})\n`);
